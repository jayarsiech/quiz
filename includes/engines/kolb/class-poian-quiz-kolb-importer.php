		$form_id = Poian_Quiz_Forms::create( __( 'سبک یادگیری کلب', 'poian-quiz' ), 'kolb' );
		if ( is_wp_error( $form_id ) || ! $form_id ) { wp_die( esc_html__( 'خطا در ساخت فرم.', 'poian-quiz' ) ); }
		Poian_Quiz_Forms::update_schema( $form_id, self::schema() );
		update_option( 'poian_quiz_kolb_form_id', $form_id, 'no' );

				wp_safe_redirect( add_query_arg( array(
			'page'      => Poian_Quiz_Admin::MAIN_SLUG,
			'view'      => 'editor',
			'form_id'   => $form_id,
			'pq_notice' => 'saved',
		), admin_url( 'admin.php' ) ) );
		exit;
	}

